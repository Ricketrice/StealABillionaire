#!/usr/bin/env python3
"""Knight's Keep NPC rigs (036 sweep): turns the owner's exported `<Name>_BuildNPC.lua` SPEC tables into the BossRigs layout the game already uses.

    python3 -I tools/keep_rigs.py [--src ~/Documents/SAB_Imports/KnightsKeep] [Name ...]

Reads  <src>/<Name>/<Name>_BuildNPC.lua (only its `local SPEC = { ... }` data table; the builder's code is NOT run: it is the same for every NPC, see docs/KEEP_NPCS.md)
Writes src/ServerStorage/BossRigs/<Name>/Data.lua      rig data (joints, parts, rest frames) in the format BossRigs.Shared.Driver / Builder use
       src/ServerStorage/BossRigs/<Name>/Clips/*.lua   Idle / Walk / Attack as Driver tracks (stride 8: t, quaternion, position)
       src/ServerStorage/BossRigs/<Name>/Assets.lua    texture ids (kept if it exists; run with --assets-file to write ids from a json {Name: {Color,Metalness,Roughness}})
The mesh assembly is BossRigs.Shared.NpcBuilder (Studio, after the owner's Import 3D). R6 part names ("Right Arm") and joint names ("Right Shoulder") are kept as exported.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "ServerStorage", "BossRigs")
DEFAULT_SRC = os.path.expanduser("~/Documents/SAB_Imports/KnightsKeep")
NAMES = ["Peasant", "Squire", "Guard", "Archer", "Crusader"]


# --- a tiny Lua table reader (numbers, strings, true/false, nested tables, name = / ["name"] = keys) -----------------------------------------
class Lua:
    def __init__(self, text):
        self.t = text
        self.i = 0

    def ws(self):
        while True:
            m = re.compile(r"\s+|--[^\n]*").match(self.t, self.i)
            if not m:
                return
            self.i = m.end()

    def value(self):
        self.ws()
        c = self.t[self.i]
        if c == "{":
            return self.table()
        if c == '"':
            j = self.t.index('"', self.i + 1)
            s = self.t[self.i + 1:j]
            self.i = j + 1
            return s
        m = re.compile(r"-?\d+\.?\d*(?:[eE][-+]?\d+)?").match(self.t, self.i)
        if m:
            self.i = m.end()
            f = float(m.group())
            return int(f) if f == int(f) and "." not in m.group() and "e" not in m.group().lower() else f
        m = re.compile(r"true|false").match(self.t, self.i)
        if m:
            self.i = m.end()
            return m.group() == "true"
        raise ValueError("unexpected %r at %d" % (self.t[self.i:self.i + 30], self.i))

    def table(self):
        self.i += 1
        items, keyed = [], {}
        while True:
            self.ws()
            if self.t[self.i] == "}":
                self.i += 1
                return keyed if keyed else items
            m = re.compile(r'\[\s*"([^"]+)"\s*\]\s*=|([A-Za-z_]\w*)\s*=(?!=)').match(self.t, self.i)
            if m:
                self.i = m.end()
                keyed[m.group(1) or m.group(2)] = self.value()
            else:
                items.append(self.value())
            self.ws()
            if self.t[self.i] in ",;":
                self.i += 1


def read_spec(path):
    text = open(path, encoding="utf-8").read()
    i = text.index("local SPEC = {") + len("local SPEC = ")
    lua = Lua(text)
    lua.i = i
    return lua.table()


# --- emit ----------------------------------------------------------------------------------------------------------------------------------
def n(x):
    if isinstance(x, int):
        return str(x)
    s = ("%.6f" % x).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def arr(xs):
    return "{ " + ", ".join(n(x) for x in xs) + " }"


def data_module(name, spec):
    hrp = spec["hrp"]
    joints = spec["joints"]
    out = ["-- Studio location: ServerStorage.BossRigs.%s.Data (ModuleScript)" % name,
           "-- GENERATED by tools/keep_rigs.py from %s_BuildNPC.lua (the owner's R6 NPC export). Do not edit by hand." % name,
           "return {",
           '\tname = "%s",' % name, '\tprefix = "%s",' % name, "\trigKind = \"R6\",", "\tstuds = 1,",
           "\thrpHeight = %s," % n(hrp["center"][1]),
           "\thrpFrame = %s," % arr([hrp["center"][0], hrp["center"][1], hrp["center"][2], 1, 0, 0, 0, 1, 0, 0, 0, 1]),
           "\thrpSize = %s," % arr(hrp["size"]),
           "\twalkSpeed = %s," % n(spec["walkSpeed"]),
           "\tneonColor = { 1, 1, 1 },",
           "\torder = { " + ", ".join('"%s"' % j["name"] for j in joints) + " },",
           "\tjoints = {"]
    for j in joints:
        out.append('\t\t["%s"] = { p0 = "%s", p1 = "%s", c0 = %s, c1 = %s },' % (j["name"], j["p0"], j["p1"], arr(j["c0"]), arr(j["c1"])))
    out += ["\t},", "\twelds = {},", "\tfx = {},", "\tspin = {},", "\tmeshBox = {},", "\tparts = {"]
    for p in spec["parts"]:
        out.append('\t\t["%s"] = { center = %s, size = %s },' % (p["name"], arr(p["center"]), arr(p["size"])))
    out += ["\t},", "}", ""]
    return "\n".join(out)


def clip_module(name, clip, spec):
    joint_of = {j["p1"]: j["name"] for j in spec["joints"]}
    keys = sorted(clip["keys"], key=lambda k: k["t"])
    length = keys[-1]["t"]
    ident = [0, 0, 0, 0, 0, 0, 1]
    out = ["-- Studio location: ServerStorage.BossRigs.%s.Clips.%s (ModuleScript)" % (name, clip["name"]),
           "-- GENERATED by tools/keep_rigs.py from %s_BuildNPC.lua. Driver tracks: { stride 8, then t, qx, qy, qz, qw, px, py, pz per key }." % name,
           "return {", "\tlength = %s," % n(length), "\tloop = %s," % ("true" if clip["loop"] else "false"), "\tjoints = {"]
    for part, jn in joint_of.items():
        rows = []
        for k in keys:
            x, y, z, qx, qy, qz, qw = k["p"].get(part, ident)
            rows += [k["t"], qx, qy, qz, qw, x, y, z]
        out.append('\t\t["%s"] = { 8, %s },' % (jn, ", ".join(n(v) for v in rows)))
    out += ["\t},", "}", ""]
    return "\n".join(out)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def main(argv):
    src = DEFAULT_SRC
    names = []
    assets_file = None
    it = iter(argv)
    for a in it:
        if a == "--src":
            src = next(it)
        elif a == "--assets-file":
            assets_file = json.load(open(next(it)))
        else:
            names.append(a)
    for name in names or NAMES:
        spec = read_spec(os.path.join(src, name, "%s_BuildNPC.lua" % name))
        manifest = os.path.join(src, name, "%s_rig.json" % name)
        if os.path.exists(manifest):  # the owner's JSON manifest must agree with the SPEC table (a cheap cross-check)
            m = json.load(open(manifest))
            flat = json.dumps(m, sort_keys=True)
            for p in spec["parts"]:
                assert p["name"] in flat, "%s: part %s is not in the rig.json manifest" % (name, p["name"])
        base = os.path.join(OUT, name)
        write(os.path.join(base, "Data.lua"), data_module(name, spec))
        for clip in spec["clips"]:
            write(os.path.join(base, "Clips", clip["name"] + ".lua"), clip_module(name, clip, spec))
        assets_path = os.path.join(base, "Assets.lua")
        ids = (assets_file or {}).get(name)
        if ids or not os.path.exists(assets_path):
            ids = ids or {}
            lines = ["-- Studio location: ServerStorage.BossRigs.%s.Assets (ModuleScript)" % name,
                     "-- Uploaded texture ids for %s (Color / Metalness / Roughness PNGs from the owner's export). A missing id keeps the imported material." % name,
                     "return {"]
            for k in ("Color", "Metalness", "Roughness"):
                if ids.get(k):
                    lines.append('\t%s = "%s",' % (k, ids[k]))
            lines += ["}", ""]
            write(assets_path, "\n".join(lines))
        print("%s: %d parts, %d joints, clips %s" % (name, len(spec["parts"]), len(spec["joints"]), ", ".join(c["name"] for c in spec["clips"])))


if __name__ == "__main__":
    main(sys.argv[1:])
